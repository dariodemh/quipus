# -*- coding: utf-8 -*-
"""Exploracion inicial: cobertura y forma de los datos para el test de mitades."""
import pandas as pd, numpy as np, re

C = pd.read_csv('analisis/datos/cuerdas.csv', dtype=str)
P = C[C.nivel == '0'].copy()
P['v'] = pd.to_numeric(P['valor'], errors='coerce')
P['tiene_nudos'] = P['nudos'].notna() & (P['nudos'].fillna('').str.strip() != '')
P['vk'] = np.where(P['tiene_nudos'], P['v'], np.nan)
P['kd'] = P['nudos'].fillna('').apply(lambda s: ''.join(re.findall(r',([SZU])\)', s)))
P['kd1'] = P['kd'].str[0]

print('--- pendantes por quipu ---')
n = P.groupby('kfg').size()
print(n.describe().round(1).to_dict())
print('quipus n>=6:', (n >= 6).sum(), ' n>=8:', (n >= 8).sum(), ' n>=10:', (n >= 10).sum())
print('--- valores ---')
print('vk no nulo por quipu (mediana):', P.groupby('kfg').vk.apply(lambda s: s.notna().mean()).median().round(3))
print('quipus con >=6 valores:', (P.groupby('kfg').vk.apply(lambda s: s.notna().sum()) >= 6).sum())
print('vk==0 share:', (P.vk == 0).mean().round(3), ' vk>0 share:', (P.vk > 0).mean().round(3))
print('max valor:', P.vk.max(), ' percentiles:', np.nanpercentile(P.vk, [50, 90, 99]).round(1))
print('--- color ---')
print('colores unicos:', P.color.nunique(), 'nulos:', P.color.isna().sum())
print(P.color.value_counts().head(12).to_dict())
print('colores con rango/parentesis:', P.color.fillna('').str.contains(r'[\(\)\-/]').mean().round(3))
print('--- direccion de nudo ---')
print('pendantes con dir:', (P.kd1 != '').sum(), 'de', len(P))
print(P.kd1.value_counts().to_dict())
print('--- torsion ---')
print(P.torsion.value_counts().to_dict())
print('--- union ---')
print(P.union.value_counts().to_dict())
print('--- quipus con variacion interna ---')
g = P.groupby('kfg')
print('dir S/Z ambas:', (g.kd1.apply(lambda s: set(s) >= {'S', 'Z'})).sum())
print('union R/V ambas:', (g.union.apply(lambda s: set(s) >= {'R', 'V'})).sum())
print('torsion S/Z ambas:', (g.torsion.apply(lambda s: set(s) >= {'S', 'Z'})).sum())
print('color >=2:', (g.color.nunique() >= 2).sum())
print('--- grupos ---')
G = pd.read_csv('analisis/datos/grupos.csv', dtype=str)
ng = G.groupby('kfg').size()
print('grupos por quipu:', ng.describe().round(1).to_dict())
print('quipus >=2 grupos:', (ng >= 2).sum(), '>=4:', (ng >= 4).sum())
