import pandas as pd
pd.set_option('display.width', 220)
pd.set_option('display.max_columns', 50)
c = pd.read_csv('analisis/datos/cuerdas.csv')
d = c[c.kfg == 'AS069'].copy()
print("n filas AS069:", len(d))
print("nivel counts:", d.nivel.value_counts().to_dict())
print("tipo counts:", d.tipo.value_counts().to_dict())
print("union counts:", d.union.value_counts(dropna=False).to_dict())
print("torsion counts:", d.torsion.value_counts(dropna=False).to_dict())
print("grupo counts (n cuerdas):", d.grupo.value_counts().sort_index().to_dict())
print("n grupos:", d.grupo.nunique())
print("largo total cm:", d.largo.sum(), "max", d.largo.max())
print("valor no-nulo:", d.valor.notna().sum(), "de", len(d))
print("cuerdas sin nudos (nudos NaN o vacio):")
print("  nudos NaN:", d.nudos.isna().sum())
print("valor==0 y nudos vacio:", ((d.valor == 0) & (d.nudos.isna())).sum())
print("color nunique:", d.color.nunique())
print("terminacion:", d.terminacion.value_counts(dropna=False).head(10).to_dict())
print(d.head(15).to_string())
