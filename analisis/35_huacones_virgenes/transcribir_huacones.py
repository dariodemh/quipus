def suma_nudos(s):
    if not s:
        return 0
    return sum(int(m.group(1)) for m in re.finditer(r",(\d+)(?:;|$)", s))


def main():
    cols = ["kfg", "orden", "cuerda", "tipo", "nivel", "padre", "grupo", "valor", "alt",
            "nudos", "color", "torsion", "union", "largo", "terminacion", "notas"]
    orden_por_k = {}
    filas = []
    for kfg, cuerda, nivel, padre, grupo, valor, nudos, color, torsion, union, largo, term, notas in CUERDAS:
        union_norm = "R" if union == "r" else union
        sn = suma_nudos(nudos)
        if sn != valor and not (kfg == "JC028" and cuerda == "p5"):
            raise AssertionError(f"Discrepancia inesperada en {kfg} {cuerda}: valor={valor}, suma_nudos={sn}")
        idx = orden_por_k.get(kfg, 0)
        orden_por_k[kfg] = idx + 1
        filas.append([
            kfg, idx, cuerda, "p", nivel, padre, grupo, valor, "",
            nudos, color, torsion, union_norm, "" if largo is None else largo, term, notas,
        ])

    out_c = OUT_DIR / "cuerdas_huacones.csv"
    with open(out_c, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols)
        w.writerows(filas)

    q_cols = ["kfg", "okr", "quipu_huacones", "inventario", "lote", "largo_pc", "bucle_pc",
              "lectura_dir", "pc_color", "n_cuerdas", "n_colgantes", "n_anudadas",
              "suma_total", "tiene_aditivas", "tiene_ro"]
    q_filas = []
    for kfg, okr, qnum, inv, lote, lpc, bucle, ldir, pcc in METADATOS:
        sub = [r for r in CUERDAS if r[0] == kfg]
        n_c = len(sub)
        n_col = sum(1 for r in sub if r[2] == 0)
        n_anu = sum(1 for r in sub if r[6])
        suma = sum(r[5] for r in sub)
        adit = any("aditiva" in r[12].lower() for r in sub)
        ro = any("RO" in r[7] for r in sub) or ("RO" in pcc)
        q_filas.append([kfg, okr, qnum, inv, lote, lpc, int(bucle), ldir, pcc, n_c, n_col, n_anu, suma, int(adit), int(ro)])

    out_q = OUT_DIR / "quipus_huacones.csv"
    with open(out_q, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(q_cols)
        w.writerows(q_filas)

    print(f"Escrito {out_c}: {len(filas)} cuerdas en {len(METADATOS)} quipus")
    print(f"Escrito {out_q}: {len(q_filas)} quipus")


